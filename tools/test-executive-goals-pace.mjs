import assert from 'node:assert/strict'
import { executiveFixture, config } from './test-executive-forecast.mjs'
import { buildEnrollmentGoals, initialEnrollmentGoals } from '../src/lib/enrollmentGoals.ts'
import { buildForecastBenchmarks } from '../src/lib/forecastBenchmarks.ts'
import { coursePipelineGaps } from '../src/lib/coursePipeline.ts'
import { dateDay } from '../src/lib/campaignForecast.ts'

const data = executiveFixture()
const sources = data.map((item) => ({ period: item.period, rows: item.matriculados }))
const goals = buildEnrollmentGoals(sources, '2026.2', { asOf: config.asOf, end: config.end })
assert.equal(goals.base, 300)
assert.equal(goals.current, 66)
assert.equal(goals.remaining, 234)
assert.equal(goals.retained, 50)
assert.equal(goals.arrivals, 16)
assert.equal(goals.rows[0].target + goals.rows[1].target, 511)
assert.equal(goals.rows[0].observed, 6)
assert.equal(goals.rows[1].observed, 0)
assert.equal(goals.rows[0].gap, 301)
assert.equal(goals.daysLeft, dateDay(config.end) - dateDay(config.asOf))
assert.equal(goals.rows[0].dailyRequired, 301 / goals.daysLeft)
const graduating = structuredClone(sources)
for (const row of graduating.find((item) => item.period === '2026.2').rows.slice(0, 20)) row.periodo = '10'
const replacement = buildEnrollmentGoals(graduating, '2026.2')
assert.equal(replacement.graduating, 20)
assert.equal(replacement.eligible, 280)
assert.equal(replacement.replacementIfAllRenew, 4)
assert.equal(replacement.oneRenewalPoint, 2.8)
const conflict = structuredClone(sources)
conflict.at(-1).rows.push({ ...conflict.at(-1).rows[0], tipo_de_ingresso: 'PROUNI' })
const ambiguous = buildEnrollmentGoals(conflict, '2026.2')
assert.equal(ambiguous.current, goals.current)
assert.equal(ambiguous.unclassifiedAdmission, 1)
assert.equal(ambiguous.rows[0].observed, 5)
assert.equal(ambiguous.rows[1].observed, 0)
const medicine = structuredClone(sources)
medicine.at(-1).rows.push({ ...medicine.at(-1).rows[0], cpf: '99999999999', curso: 'MEDICINA' })
assert.equal(buildEnrollmentGoals(medicine, '2026.2').rows[0].observed, 6)
assert.equal(buildEnrollmentGoals(medicine, '2026.2', undefined, { ...initialEnrollmentGoals, includeMedicine: true }).rows[0].observed, 7)
assert.equal(buildEnrollmentGoals([], '2026.2').remaining, null)
assert.equal(buildEnrollmentGoals(sources, '2025.2').hasInitialGoals, false)
assert.equal(buildEnrollmentGoals(sources, '2026.2', { asOf: '2027-04-01', end: config.end }).rows[0].dailyRequired, null)

const inscritos = buildForecastBenchmarks(data, config, 'inscritos')
assert.equal(inscritos.recentProjection, 60)
assert.equal(inscritos.historicalProjection, 200)
assert.equal(inscritos.current.dailyRecent, 0)
assert.equal(inscritos.usableReferences, 3)
assert.equal(inscritos.backtest.exercises.length, 1)
assert.equal(inscritos.backtest.exercises[0].period, '2026.1')
assert.equal(inscritos.backtest.exercises[0].recent, 60)
const calouros = buildForecastBenchmarks(data, config, 'calouros')
assert.equal(calouros.recentProjection, 6)
assert.equal(calouros.historicalProjection, 20)
const update = structuredClone(data)
update.at(-1).matriculados.push({ ...update.at(-1).matriculados[0], cpf: '99999999999', data_de_matricula: '06/11/2026' })
const changed = buildForecastBenchmarks(update, config, 'calouros')
assert.equal(changed.current.atCut, 7)
assert.equal(changed.current.dailyRecent, 1 / 14)
assert.equal(changed.historicalProjection, 21)
assert.ok(changed.recentProjection > calouros.recentProjection)
update.at(-1).matriculados.push({ ...update.at(-1).matriculados.at(-1) })
assert.deepEqual(buildForecastBenchmarks(update, config, 'calouros'), changed)
const future = structuredClone(data)
future.at(-1).matriculados[0].data_de_matricula = '01/02/2027'
assert.equal(buildForecastBenchmarks(future, config, 'calouros').recentProjection, null)
assert.equal(buildForecastBenchmarks(future, config, 'calouros').historicalProjection, null)
const targetFuture = structuredClone(data)
targetFuture.find((item) => item.period === '2026.1').inscritos.push({ cpf: '99999999999', data_inscricao: '02/02/2026' })
const exercise = buildForecastBenchmarks(targetFuture, config, 'inscritos').backtest.exercises[0]
assert.equal(exercise.recent, inscritos.backtest.exercises[0].recent)
assert.equal(exercise.historical, inscritos.backtest.exercises[0].historical)
assert.equal(exercise.seasonal, inscritos.backtest.exercises[0].seasonal)
assert.equal(exercise.actual, 301)
assert.equal(buildForecastBenchmarks(data, { ...config, references: [] }, 'calouros').historicalProjection, null)
assert.equal(buildForecastBenchmarks(data, { ...config, end: '2026-01-01' }, 'calouros').recentProjection, null)
const missing = structuredClone(data)
missing.at(-1).inscritos[0].data_inscricao = ''
assert.equal(buildForecastBenchmarks(missing, config, 'inscritos').recentProjection, null)
const admission = structuredClone(data)
admission.at(-1).matriculados[0].tipo_de_ingresso = 'PROUNI'
assert.equal(buildForecastBenchmarks(admission, config, 'prouni').current.atCut, 1)
assert.equal(buildForecastBenchmarks(admission, config, 'regular').current.atCut, 5)
const medicinePace = structuredClone(admission)
medicinePace.at(-1).matriculados.push({ ...medicinePace.at(-1).matriculados[0], cpf: '99999999999', curso: 'MEDICINA' })
assert.equal(buildForecastBenchmarks(medicinePace, config, 'prouni').current.atCut, 1)
assert.equal(buildForecastBenchmarks(medicinePace, config, 'calouros').current.atCut, 7)
const pipeline = coursePipelineGaps(data, config)
assert.equal(pipeline[0].total, 60)
assert.equal(pipeline[0].active, 6)
assert.equal(pipeline[0].pending, 54)
assert.ok(pipeline[0].medianWait > 0)
const repeated = structuredClone(data)
repeated.at(-1).inscritos.push({ ...repeated.at(-1).inscritos[0] })
assert.deepEqual(coursePipelineGaps(repeated, config), pipeline)
console.log('Executivo: alvo de recomposicao, reposicao de concluintes, metas 307/204, ingresso ambiguo, ritmo diario com dias zero, trecho restante historico, backtest sem vazamento e filas por curso verificados.')
