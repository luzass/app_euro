  ('postponed','Adiou o início dos estudos',false),
  ('documents','Dificuldade com documentação ou requisitos de ingresso',false),
  ('personal','Motivos pessoais',false),
  ('other','Outro',true)
on conflict(seed_key) do nothing;

create or replace function public.crm_kanban_reason_save(p_id uuid,p_name text,p_active boolean,p_requires_note boolean,p_version integer default null) returns jsonb
language plpgsql security definer set search_path='' as $$
declare old_r public.crm_kanban_loss_reasons; r public.crm_kanban_loss_reasons; normalized text;
begin
  if not public.crm_kanban_manager() then raise exception 'Somente a supervisao pode gerenciar os motivos' using errcode='42501'; end if;
  normalized:=public.crm_kanban_key(p_name);
  if normalized ~ '(semresposta|semretorno|naoresponde|naoretorn|contatoinvalido|numeroinvalido|numeroerrado|telefoneinvalido)' then
    raise exception 'Falta de resposta e contato invalido nao sao motivos de desistencia';
  end if;
  if p_id is null then
    insert into public.crm_kanban_loss_reasons(name,active,requires_note) values(btrim(p_name),p_active,p_requires_note) returning * into r;
  else
    select * into old_r from public.crm_kanban_loss_reasons where id=p_id for update;
    if not found then raise exception 'Motivo nao encontrado'; end if;
    if p_version is null or p_version<>old_r.version then raise exception 'Este motivo foi atualizado. Reabra a edicao.' using errcode='PT409'; end if;
    if old_r.seed_key='other' and not coalesce(p_requires_note,false) then raise exception 'Outro sempre exige uma observacao'; end if;
    update public.crm_kanban_loss_reasons set name=btrim(p_name),active=p_active,requires_note=p_requires_note,version=version+1,updated_at=now() where id=p_id returning * into r;
  end if;
  insert into public.crm_kanban_loss_reason_history(reason_id,actor_id,before_data,after_data) values(r.id,auth.uid(),case when old_r.id is null then null else to_jsonb(old_r) end,to_jsonb(r));
  return to_jsonb(r);
exception when unique_violation then raise exception 'Ja existe um motivo com esse nome';
end $$;

create or replace function public.crm_kanban_close_loss(p_id uuid,p_version integer,p_reason uuid,p_evidence text,p_note text default '') returns jsonb
language plpgsql security definer set search_path='' as $$
declare c public.crm_kanban_contacts; r public.crm_kanban_loss_reasons; loss jsonb;
begin
  select * into c from public.crm_kanban_contacts where id=p_id for update;
  if not found or not public.crm_kanban_can_read(c.owner_id) or not coalesce(public.crm_kanban_manager() or c.owner_id=auth.uid(),false) then raise exception 'Encerramento nao permitido' using errcode='42501'; end if;
  if p_version is null or p_version<>c.version then raise exception 'Contato atualizado. Reabra a ficha antes de encerrar.' using errcode='PT409'; end if;
  if c.loss_data is not null or c.archived then raise exception 'Este atendimento ja esta encerrado ou arquivado'; end if;
  if c.official_enrollment or c.stage='matriculado' then raise exception 'Nao registre desistencia de um atendimento matriculado'; end if;
  if p_evidence is null or p_evidence not in ('candidate_reported','staff_inferred') then raise exception 'Informe se o motivo veio do candidato ou da percepcao do atendente'; end if;
  select * into r from public.crm_kanban_loss_reasons where id=p_reason for share;
  if not found or not r.active then raise exception 'Escolha um motivo ativo'; end if;
  if r.requires_note and coalesce(length(btrim(p_note)),0)=0 then raise exception 'Este motivo exige uma observacao'; end if;
  if length(coalesce(p_note,''))>2000 then raise exception 'A observacao deve ter no maximo 2000 caracteres'; end if;
  loss:=jsonb_build_object('id',gen_random_uuid(),'reason_id',r.id,'reason_label',r.name,'evidence',p_evidence,'note',btrim(coalesce(p_note,'')),
    'closed_at',now(),'closed_by',auth.uid(),'stage',c.stage,'owner_id',c.owner_id,
    'course',c.current_data->>'curso','campus',c.current_data->>'campus','shift',c.current_data->>'turno',
    'admission',c.current_data->>'forma_ingresso','category',case when c.has_inscription then 'Inscrito' else 'Lead' end,'period','2027.1');
  update public.crm_kanban_contacts set loss_data=loss,archived=true,next_action_at=null,version=version+1,updated_at=now() where id=p_id returning * into c;
  insert into public.crm_kanban_events(contact_id,event_type,actor_id,payload) values(p_id,'loss_closed',auth.uid(),loss);
  return to_jsonb(c);
end $$;

create or replace function public.crm_kanban_reopen_loss(p_id uuid,p_version integer,p_note text) returns jsonb
language plpgsql security definer set search_path='' as $$
declare c public.crm_kanban_contacts; previous jsonb;
begin
  select * into c from public.crm_kanban_contacts where id=p_id for update;
  if not found or not public.crm_kanban_can_read(c.owner_id) or not coalesce(public.crm_kanban_manager() or c.owner_id=auth.uid(),false) then raise exception 'Reabertura nao permitida' using errcode='42501'; end if;
  if p_version is null or p_version<>c.version then raise exception 'Contato atualizado. Reabra a ficha.' using errcode='PT409'; end if;
  if c.loss_data is null then raise exception 'Este contato nao tem desistencia ativa'; end if;
  if coalesce(length(btrim(p_note)),0) not between 3 and 2000 then raise exception 'Informe uma observacao de reabertura entre 3 e 2000 caracteres'; end if;
  previous:=c.loss_data;
  update public.crm_kanban_contacts set loss_data=null,archived=false,next_action_at=null,stage_entered_at=now(),
    version=version+1,updated_at=now(),position=-nextval('public.crm_kanban_position_seq')::double precision*1024 where id=p_id;
  perform public.crm_kanban_route_contact(p_id);
  select * into c from public.crm_kanban_contacts where id=p_id;
  insert into public.crm_kanban_events(contact_id,event_type,actor_id,payload) values(p_id,'loss_reopened',auth.uid(),jsonb_build_object('previous',previous,'note',btrim(p_note),'stage',c.stage));
  return to_jsonb(c);
end $$;

create or replace function public.crm_kanban_loss_guard() returns trigger
language plpgsql security definer set search_path='' as $$
begin
  if old.loss_data is not null and new.loss_data is not null then
    if not new.archived then raise exception 'Use Reabrir atendimento para preservar o historico da desistencia'; end if;
    if new.stage is distinct from old.stage and not (new.stage='matriculado' and exists(select 1 from public.crm_kanban_sources s where s.contact_id=new.id and s.source='matriculados_20271' and public.crm_kanban_key(s.payload->>'contrato') in ('ativo','contratoativo'))) then raise exception 'Reabra o atendimento antes de mudar sua etapa'; end if;
    if new.checklist is distinct from old.checklist then raise exception 'Reabra o atendimento antes de retomar cadencias'; end if;
  end if;
  return new;
end $$;
