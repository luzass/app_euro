-- SQL - CRM Kanban Unieuro: estrutura, historico e permissoes
-- Nao apaga nem altera leads_cursos, inscritos, matriculados ou registro_crm.
-- Execute no SQL Editor do Supabase. A carga inicial fica no segundo SQL.
begin;

create table if not exists public.crm_kanban_config (
  id boolean primary key default true check (id),
  cutoff date not null default '2026-11-13',
  include_history boolean not null default true,
  history_limit integer not null default 200 check (history_limit between 0 and 200),
  last_sync_at timestamptz, last_sync_result jsonb not null default '{}'
);
insert into public.crm_kanban_config(id) values (true) on conflict do nothing;
create sequence if not exists public.crm_kanban_position_seq;

create table if not exists public.crm_kanban_contacts (
  id uuid primary key default gen_random_uuid(),
  cpf text not null unique check (cpf ~ '^[0-9]{11}$' and cpf !~ '^0+$'),
  owner_id uuid references public.profiles(id),
  stage text not null default 'primeiro_contato' check (stage in ('primeiro_contato','abordagem','negociacao','fechamento','vestibular','matriculado')),
  position double precision not null default (-nextval('public.crm_kanban_position_seq')::double precision * 1024),
  source_data jsonb not null default '{}' check (jsonb_typeof(source_data) = 'object'),
  manual_data jsonb not null default '{}' check (jsonb_typeof(manual_data) = 'object'),
  current_data jsonb generated always as (source_data || manual_data) stored,
  has_inscription boolean not null default false,
  official_enrollment boolean not null default false,
  test_only boolean not null default false,
  archived boolean not null default false,
  checklist jsonb not null default '{}' check (jsonb_typeof(checklist) = 'object'),
  next_action_at timestamptz,
  stage_entered_at timestamptz not null default now(),
  version integer not null default 1,
  created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create index if not exists crm_kanban_contacts_owner_stage_idx on public.crm_kanban_contacts(owner_id, stage, position);

create table if not exists public.crm_kanban_sources (
  source text not null check (source in ('leads_cursos','inscritos_20271','matriculados_20271')),
  source_key text not null,
  contact_id uuid not null references public.crm_kanban_contacts(id) on delete cascade,
  source_date date not null, is_test boolean not null,
  payload jsonb not null, payload_hash text not null,
  canonical_data jsonb not null, observed_at timestamptz not null default now(),
  primary key(source, source_key)
);
create index if not exists crm_kanban_sources_contact_idx on public.crm_kanban_sources(contact_id);
create table if not exists public.crm_kanban_events (
  id bigint generated by default as identity primary key,
  contact_id uuid not null references public.crm_kanban_contacts(id) on delete cascade,
  event_type text not null, actor_id uuid references public.profiles(id),
  payload jsonb not null default '{}', created_at timestamptz not null default now()
);
create index if not exists crm_kanban_events_contact_idx on public.crm_kanban_events(contact_id, id desc);
create table if not exists public.crm_kanban_activities (
  id uuid primary key default gen_random_uuid(),
  contact_id uuid not null references public.crm_kanban_contacts(id) on delete cascade,
  author_id uuid not null references public.profiles(id),
  note text not null check (length(btrim(note)) between 1 and 10000),
  channel text not null check (channel in ('whatsapp','telefone','email','presencial','outro')),
  occurred_at timestamptz not null, updated_at timestamptz not null default now()
);
create index if not exists crm_kanban_activities_contact_idx on public.crm_kanban_activities(contact_id, occurred_at desc);
create table if not exists public.crm_kanban_test_sample (cpf text primary key);

create or replace function public.crm_kanban_role() returns text
language sql stable security definer set search_path = '' as $$
  select role from public.profiles where id = auth.uid()
$$;
create or replace function public.crm_kanban_manager() returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(public.crm_kanban_role() in ('admin','reitoria','captacao_gerente'), false)
$$;
create or replace function public.crm_kanban_can_read(p_owner uuid) returns boolean
language sql stable security definer set search_path = '' as $$
  select coalesce(public.crm_kanban_role() in ('admin','reitoria','captacao_gerente','captacao','funcionario')
    and (public.crm_kanban_manager() or p_owner = auth.uid() or p_owner is null), false)
$$;
create or replace function public.crm_kanban_key(p text) returns text
language sql immutable set search_path = '' as $$
  select regexp_replace(translate(lower(coalesce(p,'')), 'áàãâäéèêëíìîïóòõôöúùûüçñ', 'aaaaaeeeeiiiiooooouuuucn'), '[^a-z0-9]', '', 'g')
$$;
create or replace function public.crm_kanban_pick(p jsonb, variadic names text[]) returns text
language plpgsql immutable set search_path = '' as $$
declare n text; k text; v text;
begin
  foreach n in array names loop
    for k,v in select key, value from jsonb_each_text(p) loop
      if public.crm_kanban_key(k) = public.crm_kanban_key(n)
        and nullif(btrim(v), '') is not null and public.crm_kanban_key(v) not in ('naoinformado','null')
        and btrim(v) !~ '^[-[:space:]]+$' then return btrim(v); end if;
    end loop;
  end loop;
  return null;
end $$;
create or replace function public.crm_kanban_cpf(p text) returns text
language sql immutable set search_path = '' as $$
  select case when coalesce(p,'') ~ '^[0-9.\-[:space:]]+$'
    and regexp_replace(coalesce(p,''), '[^0-9]', '', 'g') ~ '^[0-9]{1,11}$'
    and regexp_replace(coalesce(p,''), '[^0-9]', '', 'g') !~ '^0+$'
    then lpad(regexp_replace(p, '[^0-9]', '', 'g'),11,'0') else null end
$$;
create or replace function public.crm_kanban_date(p text) returns date
language plpgsql immutable set search_path = '' as $$
declare m text[];
begin
  if p ~ '^\d{4}-\d{2}-\d{2}T.*(Z|[+-]\d{2}:?\d{2})$' then
    return (p::timestamptz at time zone 'America/Sao_Paulo')::date;
  end if;
  m := regexp_match(p, '^(\d{4})-(\d{2})-(\d{2})');
  if m is not null then return make_date(m[1]::int,m[2]::int,m[3]::int); end if;
  m := regexp_match(p, '^(\d{1,2})/(\d{1,2})/(\d{4})');
  if m is not null then return make_date(m[3]::int,m[2]::int,m[1]::int); end if;
  return null;
exception when others then return null;
end $$;
create or replace function public.crm_kanban_canonical(p_source text, p jsonb) returns jsonb
language sql immutable set search_path = '' as $$
  select jsonb_strip_nulls(jsonb_build_object(
    'nome',public.crm_kanban_pick(p,'nome','candidato','aluno','nome_completo','name'),
    'telefone',public.crm_kanban_pick(p,'contato_principal','contato_2','telefone','celular','whatsapp','phone'),
    'curso',public.crm_kanban_pick(p,'curso','curso_interesse','Curso de interesse','nome_curso'), 'campus',public.crm_kanban_pick(p,'campus','filial','unidade','local'),
    'turno',public.crm_kanban_pick(p,'turno'),
    'forma_ingresso',public.crm_kanban_pick(p,'forma_de_ingresso','tipo_de_ingresso','forma_ingresso'),
    'email',public.crm_kanban_pick(p,'email'), 'data_de_nascimento',public.crm_kanban_pick(p,'data_de_nascimento'),
    'bairro',public.crm_kanban_pick(p,'bairro'), 'cidade',public.crm_kanban_pick(p,'cidade'),
    'estado',public.crm_kanban_pick(p,'estado'), 'observacao',public.crm_kanban_pick(p,'observacao_captacao'),
    'data_inscricao',case when p_source = 'inscritos_20271' then public.crm_kanban_pick(p,'data_inscricao') end,
    'etapa_atual',case when p_source = 'inscritos_20271' then public.crm_kanban_pick(p,'etapa_atual') end,
    'data_matricula',case when p_source = 'matriculados_20271' then public.crm_kanban_pick(p,'data_baixa_do_pagamento','data_de_matricula') end
  ))
$$;
create or replace function public.crm_kanban_refresh(p_id uuid) returns void
language plpgsql security definer set search_path = '' as $$
declare d jsonb;
begin
  select coalesce(jsonb_object_agg(k,v order by case s.source when 'leads_cursos' then 1 when 'inscritos_20271' then 2 else 3 end,s.source_date,s.source_key),'{}')
  into d from public.crm_kanban_sources s cross join lateral jsonb_each(s.canonical_data) as e(k,v)
  where s.contact_id = p_id;
  update public.crm_kanban_contacts c set source_data = d,
    has_inscription = exists(select 1 from public.crm_kanban_sources s where s.contact_id=p_id and s.source='inscritos_20271'),
    updated_at=now(), version=version+1 where c.id=p_id;
end $$;

create or replace function public.crm_kanban_import(p_source text,p_key text,p_raw jsonb,p_date date,p_test boolean) returns boolean
language plpgsql security definer set search_path = '' as $$
declare person public.crm_kanban_contacts; old_source public.crm_kanban_sources; v_cpf text; v_hash text; hint text; v_owner uuid; enrolled boolean;
begin
  v_cpf := public.crm_kanban_cpf(public.crm_kanban_pick(p_raw,'cpf'));
  if v_cpf is null then raise exception 'CPF invalido'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_cpf,731));
  select * into old_source from public.crm_kanban_sources where source=p_source and source_key=p_key for update;
  if found and (select cpf from public.crm_kanban_contacts where id=old_source.contact_id) <> v_cpf then
    raise exception 'A chave de origem mudou de CPF; precisa de revisao, sem mesclagem automatica';
  end if;
  v_hash := md5(p_raw::text);
  if old_source.payload_hash = v_hash then return false; end if;
  select * into person from public.crm_kanban_contacts where cpf=v_cpf for update;
  if not found then
    -- Aproveita o responsavel da landing page somente com correspondencia unica no perfil.
    hint := public.crm_kanban_key(public.crm_kanban_pick(p_raw,'vendedor_crm','vendedor'));
    if hint <> '' then
      select case when count(*)=1 then (array_agg(id))[1] end into v_owner from public.profiles
      where role in ('captacao','funcionario','captacao_gerente')
        and (public.crm_kanban_key(nome)=hint or public.crm_kanban_key(split_part(nome,' ',1))=hint);
    end if;
    insert into public.crm_kanban_contacts(cpf,owner_id,test_only) values(v_cpf,v_owner,p_test) returning * into person;
    insert into public.crm_kanban_events(contact_id,event_type,payload)
      values(person.id,'created',jsonb_build_object('source',p_source,'stage','primeiro_contato','is_test',p_test));
  end if;
  insert into public.crm_kanban_sources(source,source_key,contact_id,source_date,is_test,payload,payload_hash,canonical_data)
    values(p_source,p_key,person.id,p_date,p_test,p_raw,v_hash,public.crm_kanban_canonical(p_source,p_raw))
  on conflict(source,source_key) do update set payload=excluded.payload,payload_hash=excluded.payload_hash,
    source_date=excluded.source_date,is_test=excluded.is_test,canonical_data=excluded.canonical_data,observed_at=now();
  insert into public.crm_kanban_events(contact_id,event_type,payload) values(person.id,'source_update',
    jsonb_build_object('source',p_source,'source_key',p_key,'before',old_source.payload,'after',p_raw,'is_test',p_test));
  update public.crm_kanban_contacts set test_only=test_only and p_test where id=person.id;
  perform public.crm_kanban_refresh(person.id);
  if p_source='matriculados_20271' then
    select exists(select 1 from public.crm_kanban_sources s where s.contact_id=person.id and s.source='matriculados_20271'
      and public.crm_kanban_key(public.crm_kanban_pick(s.payload,'contrato')) in ('ativo','contratoativo')) into enrolled;
    if enrolled and not person.official_enrollment and person.stage <> 'matriculado' then
      insert into public.crm_kanban_events(contact_id,event_type,payload) values(person.id,'stage',
        jsonb_build_object('from',person.stage,'to','matriculado','reason','Matrícula ativa localizada na base oficial'));
      update public.crm_kanban_contacts set stage='matriculado',stage_entered_at=now(),position=-nextval('public.crm_kanban_position_seq')::double precision*1024 where id=person.id;
    end if;
    update public.crm_kanban_contacts set official_enrollment=enrolled where id=person.id;
  end if;
  return true;
end $$;

create or replace function public.crm_kanban_sync() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare cfg public.crm_kanban_config; r record; n integer:=0; unchanged integer:=0; failures integer:=0; skipped integer:=0; missing text[]:='{}'; result jsonb; conflict_details jsonb:='[]';
begin
  if not public.crm_kanban_manager() and not (auth.uid() is null and
    (coalesce(auth.role(),'')='service_role' or coalesce(auth.role(),'')='' and session_user in ('postgres','supabase_admin'))) then
    raise exception 'Somente gestores ou rotina do banco podem sincronizar' using errcode='42501';
  end if;
  if not pg_try_advisory_xact_lock(hashtextextended('crm_kanban_sync',731)) then return jsonb_build_object('busy',true); end if;
  select * into cfg from public.crm_kanban_config where id for update;
  drop table if exists pg_temp.crm_kanban_queue;
  create temporary table crm_kanban_queue(source text,source_key text,raw jsonb,cpf text,source_date date) on commit drop;
  if to_regclass('public.inscritos_20271') is not null then
    execute $q$insert into pg_temp.crm_kanban_queue
      select 'inscritos_20271',public.crm_kanban_pick(d,'chave_inscricao','id'),d,
        public.crm_kanban_cpf(public.crm_kanban_pick(d,'cpf')),public.crm_kanban_date(public.crm_kanban_pick(d,'data_inscricao'))
      from (select to_jsonb(i) d from public.inscritos_20271 i) x
      where public.crm_kanban_key(public.crm_kanban_pick(d,'curso')) <> 'medicina'
        and regexp_replace(coalesce(public.crm_kanban_pick(d,'ano_semestre'),'2027.1'),'[./[:space:]-]','','g')='20271'$q$;
  else missing:=array_append(missing,'inscritos_20271'); end if;
  if to_regclass('public.leads_cursos') is not null then
    execute $q$insert into pg_temp.crm_kanban_queue
      select 'leads_cursos',public.crm_kanban_pick(d,'id'),d,
        public.crm_kanban_cpf(public.crm_kanban_pick(d,'cpf')),public.crm_kanban_date(public.crm_kanban_pick(d,'created_at','data_criacao','data'))
      from (select to_jsonb(l) d from public.leads_cursos l) x$q$;
  else missing:=array_append(missing,'leads_cursos'); end if;
  select count(*) into skipped from pg_temp.crm_kanban_queue where cpf is null or source_date is null or source_key is null;
  delete from pg_temp.crm_kanban_queue where cpf is null or source_date is null or source_key is null;
  if cfg.include_history then
    insert into public.crm_kanban_test_sample(cpf)
    select q.cpf from pg_temp.crm_kanban_queue q
    where q.source_date < cfg.cutoff and not exists(select 1 from public.crm_kanban_test_sample s where s.cpf=q.cpf)
      and not exists(select 1 from pg_temp.crm_kanban_queue real_q where real_q.cpf=q.cpf and real_q.source_date>=cfg.cutoff)
    group by q.cpf order by max(q.source_date) desc,q.cpf
    limit greatest(0,cfg.history_limit-(select count(*) from public.crm_kanban_test_sample))
    on conflict do nothing;
  end if;
  for r in select q.* from pg_temp.crm_kanban_queue q where q.source_date>=cfg.cutoff or cfg.include_history and
    (exists(select 1 from public.crm_kanban_test_sample s where s.cpf=q.cpf)
      or exists(select 1 from pg_temp.crm_kanban_queue real_q where real_q.cpf=q.cpf and real_q.source_date>=cfg.cutoff))
    order by q.source_date,case q.source when 'leads_cursos' then 1 else 2 end,q.source_key,md5(q.raw::text)
  loop
    begin
      if public.crm_kanban_import(r.source,r.source_key,r.raw,r.source_date,r.source_date<cfg.cutoff) then n:=n+1; else unchanged:=unchanged+1; end if;
    exception when others then
      failures:=failures+1;
      if jsonb_array_length(conflict_details)<20 then conflict_details:=conflict_details || jsonb_build_array(jsonb_build_object('source',r.source,'source_key',r.source_key,'reason',sqlerrm)); end if;
    end;
  end loop;
  -- Matriculas enriquecem apenas pessoas ja existentes: nunca criam novos cards.
  if to_regclass('public.matriculados_20271') is not null then
    for r in execute $q$select d,public.crm_kanban_pick(d,'chave_unica','id') source_key
      from (select to_jsonb(m) d from public.matriculados_20271 m) x
      where public.crm_kanban_key(public.crm_kanban_pick(d,'curso')) <> 'medicina'
        and public.crm_kanban_pick(d,'chave_unica','id') is not null
        and regexp_replace(coalesce(public.crm_kanban_pick(d,'periodo_letivo'),''),'[./[:space:]-]','','g')='20271'
        and exists(select 1 from public.crm_kanban_contacts c where c.cpf=public.crm_kanban_cpf(public.crm_kanban_pick(d,'cpf')))$q$
    loop
      begin
        if public.crm_kanban_import('matriculados_20271',r.source_key,r.d,
          coalesce(public.crm_kanban_date(public.crm_kanban_pick(r.d,'data_baixa_do_pagamento','data_de_matricula')),cfg.cutoff),
          (select test_only from public.crm_kanban_contacts where cpf=public.crm_kanban_cpf(public.crm_kanban_pick(r.d,'cpf')))) then n:=n+1; else unchanged:=unchanged+1; end if;
      exception when others then
        failures:=failures+1;
        if jsonb_array_length(conflict_details)<20 then conflict_details:=conflict_details || jsonb_build_array(jsonb_build_object('source','matriculados_20271','source_key',r.source_key,'reason',sqlerrm)); end if;
      end;
    end loop;
  else missing:=array_append(missing,'matriculados_20271'); end if;
  result:=jsonb_build_object('updated',n,'unchanged',unchanged,'conflicts',failures,'invalid',skipped,'missing_sources',missing,'conflict_details',conflict_details);
  update public.crm_kanban_config set last_sync_at=now(),last_sync_result=result where id;
  return result;
end $$;

create or replace function public.crm_kanban_validate_data(p jsonb) returns jsonb
language plpgsql immutable set search_path = '' as $$
declare k text; v jsonb;
begin
  if jsonb_typeof(p)<>'object' then raise exception 'Dados do contato invalidos'; end if;
  for k,v in select * from jsonb_each(p) loop
    if k not in ('nome','telefone','curso','campus','turno','forma_ingresso','email','data_de_nascimento','bairro','cidade','estado','observacao')
      or jsonb_typeof(v) not in ('string','null') or length(coalesce(v#>>'{}',''))>10000 then raise exception 'Campo nao permitido ou invalido: %',k; end if;
  end loop;
  if p ? 'nome' and coalesce(btrim(p->>'nome'),'')='' then raise exception 'Informe o nome'; end if;
  if p ? 'telefone' and coalesce(p->>'telefone','')<>'' and length(regexp_replace(p->>'telefone','[^0-9]','','g')) not between 10 and 15 then raise exception 'Telefone invalido'; end if;
  if coalesce(p->>'data_de_nascimento','')<>'' and public.crm_kanban_date(p->>'data_de_nascimento') is null then raise exception 'Nascimento invalido'; end if;
  return p;
end $$;

create or replace function public.crm_kanban_save(p_id uuid,p_patch jsonb,p_version integer) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare c public.crm_kanban_contacts; after_c public.crm_kanban_contacts; v_owner uuid; k text;
begin
  select * into c from public.crm_kanban_contacts where id=p_id for update;
  if not found or not public.crm_kanban_can_read(c.owner_id) then raise exception 'Contato indisponivel para este usuario' using errcode='42501'; end if;
  if p_version is null or c.version<>p_version then raise exception 'Este contato foi atualizado. Atualize o quadro e tente novamente.' using errcode='40001'; end if;
  if jsonb_typeof(p_patch)<>'object' then raise exception 'Alteracao invalida'; end if;
  for k in select jsonb_object_keys(p_patch) loop
    if k not in ('owner_id','stage','position','manual_data','next_action_at','archived','checklist') then raise exception 'Alteracao nao permitida: %',k; end if;
  end loop;
  v_owner:=c.owner_id;
  if p_patch ? 'owner_id' then
    v_owner:=nullif(p_patch->>'owner_id','')::uuid;
    if not public.crm_kanban_manager() and not (c.owner_id is null and v_owner=auth.uid()) and v_owner is distinct from c.owner_id then
      raise exception 'Vendedores nao podem transferir responsaveis' using errcode='42501';
    end if;
    if v_owner is not null and not exists(select 1 from public.profiles where id=v_owner and role in ('captacao','funcionario','captacao_gerente')) then raise exception 'Responsavel nao habilitado para captacao'; end if;
  end if;
  if not public.crm_kanban_manager() and (v_owner is null or v_owner<>auth.uid()) then raise exception 'Assuma o contato antes de registrar atendimento' using errcode='42501'; end if;
  if p_patch ? 'manual_data' then perform public.crm_kanban_validate_data(p_patch->'manual_data'); end if;
  if p_patch ? 'position' and coalesce(p_patch->>'position','') !~ '^-?[0-9]+(\.[0-9]+)?$' then raise exception 'Posicao invalida'; end if;
  update public.crm_kanban_contacts set owner_id=v_owner,
    stage=case when p_patch ? 'stage' then p_patch->>'stage' else stage end,
    stage_entered_at=case when p_patch ? 'stage' and stage<>p_patch->>'stage' then now() else stage_entered_at end,
    position=case when p_patch ? 'position' then (p_patch->>'position')::double precision
      when p_patch ? 'stage' and stage<>p_patch->>'stage' then -nextval('public.crm_kanban_position_seq')::double precision*1024 else position end,
    manual_data=manual_data || coalesce(p_patch->'manual_data','{}'),
    next_action_at=case when p_patch ? 'next_action_at' then nullif(p_patch->>'next_action_at','')::timestamptz else next_action_at end,
    archived=case when p_patch ? 'archived' then (p_patch->>'archived')::boolean else archived end,
    checklist=case when p_patch ? 'checklist' then p_patch->'checklist' else checklist end,
    version=version+1,updated_at=now() where id=p_id returning * into after_c;
  if c.stage<>after_c.stage then
    insert into public.crm_kanban_events(contact_id,event_type,actor_id,payload) values(p_id,'stage',auth.uid(),jsonb_build_object('from',c.stage,'to',after_c.stage));
  end if;
  if c.owner_id is distinct from after_c.owner_id then
    insert into public.crm_kanban_events(contact_id,event_type,actor_id,payload) values(p_id,'assignment',auth.uid(),jsonb_build_object('from',c.owner_id,'to',after_c.owner_id));
  end if;
  if (p_patch - 'stage' - 'owner_id' - 'position')<>'{}' then
    insert into public.crm_kanban_events(contact_id,event_type,actor_id,payload) values(p_id,'edited',auth.uid(),jsonb_build_object('before',c.current_data,'after',after_c.current_data,'changes',p_patch-'manual_data'));
  end if;
  return to_jsonb(after_c);
end $$;

create or replace function public.crm_kanban_create(p_cpf text,p_data jsonb,p_owner uuid default null) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare v_cpf text; c public.crm_kanban_contacts; v_owner uuid;
begin
  if not public.crm_kanban_can_read(null) or auth.uid() is null then raise exception 'Acesso negado' using errcode='42501'; end if;
  v_cpf:=public.crm_kanban_cpf(p_cpf);
  if v_cpf is null or length(regexp_replace(coalesce(p_cpf,''),'[^0-9]','','g'))<>11 then raise exception 'CPF obrigatorio com 11 digitos'; end if;
  perform public.crm_kanban_validate_data(p_data);
  if coalesce(btrim(p_data->>'nome'),'')='' then raise exception 'Informe o nome'; end if;
  perform pg_advisory_xact_lock(hashtextextended(v_cpf,731));
  select * into c from public.crm_kanban_contacts where cpf=v_cpf for update;
  if found then
    if not public.crm_kanban_can_read(c.owner_id) then raise exception 'Este CPF ja possui atendimento. Procure o gestor para conferir o responsavel.' using errcode='42501'; end if;
    select coalesce(jsonb_object_agg(k,v),'{}') into p_data from jsonb_each(p_data) e(k,v)
      where v<>'null'::jsonb and nullif(btrim(v#>>'{}'),'') is not null;
    perform public.crm_kanban_save(c.id,jsonb_build_object('manual_data',p_data,'owner_id',case when public.crm_kanban_manager() then coalesce(p_owner,c.owner_id) else auth.uid() end),c.version);
    update public.crm_kanban_contacts set test_only=false where id=c.id returning * into c;
    insert into public.crm_kanban_events(contact_id,event_type,actor_id,payload) values(c.id,'manual_registration',auth.uid(),jsonb_build_object('source','manual','data',p_data));
    return to_jsonb(c);
  end if;
  v_owner:=case when public.crm_kanban_manager() then p_owner else auth.uid() end;
  if not public.crm_kanban_manager() and p_owner is not null and p_owner<>auth.uid() then raise exception 'Vendedor nao pode atribuir outro responsavel' using errcode='42501'; end if;
  if v_owner is not null and not exists(select 1 from public.profiles where id=v_owner and role in ('captacao','funcionario','captacao_gerente')) then raise exception 'Responsavel nao habilitado'; end if;
  insert into public.crm_kanban_contacts(cpf,manual_data,owner_id) values(v_cpf,p_data,v_owner) returning * into c;
  insert into public.crm_kanban_events(contact_id,event_type,actor_id,payload) values(c.id,'created',auth.uid(),jsonb_build_object('source','manual','stage',c.stage,'data',p_data));
  return to_jsonb(c);
end $$;

create or replace function public.crm_kanban_activity(p_contact uuid,p_note text,p_channel text,p_occurred timestamptz,p_activity uuid default null) returns uuid
language plpgsql security definer set search_path = '' as $$
declare c public.crm_kanban_contacts; a public.crm_kanban_activities; new_id uuid;
begin
  select * into c from public.crm_kanban_contacts where id=p_contact for update;
  if not found or not public.crm_kanban_can_read(c.owner_id) or not coalesce(public.crm_kanban_manager() or c.owner_id=auth.uid(),false) then raise exception 'Atendimento nao permitido' using errcode='42501'; end if;
  if p_occurred is null or p_occurred>now()+interval '5 minutes' then raise exception 'Use uma data de atendimento ja realizado'; end if;
  if p_activity is not null then
    select * into a from public.crm_kanban_activities where id=p_activity and contact_id=p_contact for update;
    if not found or not(public.crm_kanban_manager() or a.author_id=auth.uid()) then raise exception 'Edicao de atendimento nao permitida' using errcode='42501'; end if;
    update public.crm_kanban_activities set note=btrim(p_note),channel=p_channel,occurred_at=p_occurred,updated_at=now() where id=p_activity;
    new_id:=p_activity;
  else
    insert into public.crm_kanban_activities(contact_id,author_id,note,channel,occurred_at) values(p_contact,auth.uid(),btrim(p_note),p_channel,p_occurred) returning id into new_id;
  end if;
  insert into public.crm_kanban_events(contact_id,event_type,actor_id,payload) values(p_contact,'activity',auth.uid(),
    jsonb_build_object('activity_id',new_id,'before',to_jsonb(a),'note',btrim(p_note),'channel',p_channel,'occurred_at',p_occurred));
  update public.crm_kanban_contacts set updated_at=now(),version=version+1 where id=p_contact;
  return new_id;
end $$;

create or replace function public.crm_kanban_workspace() returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare config_data jsonb;
begin
  if not public.crm_kanban_can_read(null) then raise exception 'Acesso negado' using errcode='42501'; end if;
  select to_jsonb(c) into config_data from public.crm_kanban_config c where id;
  if not public.crm_kanban_manager() then config_data:=jsonb_set(config_data,'{last_sync_result}',(config_data->'last_sync_result')-'conflict_details'); end if;
  return jsonb_build_object('config',config_data,
    'members',(select coalesce(jsonb_agg(jsonb_build_object('id',id,'nome',nome,'role',role) order by nome),'[]')
      from public.profiles where role in ('captacao','funcionario','captacao_gerente','admin','reitoria')));
