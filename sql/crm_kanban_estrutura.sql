create or replace function public.crm_kanban_detail(p_id uuid,p_before bigint default null) returns jsonb
language plpgsql stable security definer set search_path = '' as $$
declare c public.crm_kanban_contacts;
begin
  select * into c from public.crm_kanban_contacts where id=p_id;
  if not found or not public.crm_kanban_can_read(c.owner_id) then raise exception 'Contato indisponivel' using errcode='42501'; end if;
  return jsonb_build_object('contact',to_jsonb(c),
    'sources',(select coalesce(jsonb_agg(to_jsonb(s) order by source_date desc),'[]') from public.crm_kanban_sources s where contact_id=p_id),
    'activities',(select coalesce(jsonb_agg(to_jsonb(a) order by occurred_at desc),'[]') from public.crm_kanban_activities a where contact_id=p_id),
    'events',(select coalesce(jsonb_agg(to_jsonb(e) order by id desc),'[]') from
      (select * from public.crm_kanban_events where contact_id=p_id and (p_before is null or id<p_before) order by id desc limit 50) e),
    'visited_stages',(select coalesce(jsonb_agg(distinct phase),'[]') from (
      select payload->>'from' phase from public.crm_kanban_events where contact_id=p_id and event_type='stage'
      union select payload->>'to' from public.crm_kanban_events where contact_id=p_id and event_type='stage'
      union select payload->>'stage' from public.crm_kanban_events where contact_id=p_id and event_type='created'
      union select c.stage
    ) phases where phase is not null));
end $$;

-- Base desidentificada: nunca devolve nomes, CPF real, telefone, email ou nascimento.
create or replace function public.crm_kanban_persona_rows() returns jsonb
language plpgsql security definer set search_path = '' as $$
declare ps text; q text:=''; missing text[]:='{}'; result jsonb;
begin
  if not public.crm_kanban_can_read(null) then raise exception 'Acesso negado' using errcode='42501'; end if;
  foreach ps in array array['20241','20242','20251','20252','20261','20262'] loop
    if to_regclass('public.matriculados_'||ps) is null then missing:=array_append(missing,ps);
    else q:=q || case when q='' then '' else ' union all ' end || format('select to_jsonb(m) d from public.%I m','matriculados_'||ps); end if;
  end loop;
  if q='' then return jsonb_build_object('rows','[]'::jsonb,'missing',missing); end if;
  execute $q$
    with raw as ($q$ || q || $q$), cleaned as (
      select d, public.crm_kanban_cpf(public.crm_kanban_pick(d,'cpf')) cpf,
        public.crm_kanban_key(public.crm_kanban_pick(d,'curso')) course_key,
        regexp_replace(coalesce(public.crm_kanban_pick(d,'periodo_letivo'),''),'[^0-9]','','g') ps
      from raw where public.crm_kanban_key(public.crm_kanban_pick(d,'contrato')) in ('ativo','contratoativo')
        and public.crm_kanban_key(public.crm_kanban_pick(d,'tipo_aluno'))='calouro'
        and public.crm_kanban_key(public.crm_kanban_pick(d,'nivel_de_ensino')) !~ '(posgraduacao|extensao|mestrado|doutorado)'
    ), people as (
      select distinct on (cpf,course_key) * from cleaned
      where cpf is not null and course_key<>'' and ps in ('20241','20242','20251','20252','20261','20262')
      order by cpf,course_key,ps desc,d::text
    ), features as (
      select row_number() over(order by course_key,ps,cpf) rn, d,ps,
        public.crm_kanban_date(public.crm_kanban_pick(d,'data_de_nascimento')) birth,
        public.crm_kanban_date(public.crm_kanban_pick(d,'data_de_matricula')) enrolled
      from people
    )
    select jsonb_build_object('rows',coalesce(jsonb_agg(jsonb_build_object(
      'cpf',lpad(rn::text,11,'0'),'curso',public.crm_kanban_pick(d,'curso'),
      'periodo_letivo',left(ps,4)||'.'||right(ps,1),'tipo_aluno','CALOURO','contrato','ATIVO',
      'filial',public.crm_kanban_pick(d,'filial','campus'),'turno',public.crm_kanban_pick(d,'turno'),
      'tipo_de_ingresso',public.crm_kanban_pick(d,'tipo_de_ingresso'),
      'idade_matricula',case when birth is not null and enrolled>=birth then extract(year from age(enrolled,birth))::int
        when coalesce(public.crm_kanban_pick(d,'idade_matricula'),'') ~ '^[0-9]{1,3}$' then public.crm_kanban_pick(d,'idade_matricula')::int end
    ) order by rn),'[]'), 'missing',to_jsonb($1::text[])) from features
  $q$ into result using missing;
  return result;
end $$;

