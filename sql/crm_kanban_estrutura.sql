create or replace function public.crm_kanban_finish_tests(p_confirmation text) returns jsonb
language plpgsql security definer set search_path = '' as $$
declare removed integer; id_to_refresh uuid;
begin
  if not coalesce(public.crm_kanban_role()='admin',false) and not
    (auth.uid() is null and coalesce(auth.role(),'')='' and session_user in ('postgres','supabase_admin')) then
    raise exception 'Somente admin pode encerrar os testes' using errcode='42501'; end if;
  if p_confirmation is distinct from 'ENCERRAR TESTES 13/11/2026' then raise exception 'Confirmacao obrigatoria para remover os contatos de teste'; end if;
  perform pg_advisory_xact_lock(hashtextextended('crm_kanban_sync',731));
  update public.crm_kanban_config set include_history=false where id;
  delete from public.crm_kanban_contacts where test_only;
  get diagnostics removed = row_count;
  for id_to_refresh in select distinct contact_id from public.crm_kanban_sources where is_test loop
    delete from public.crm_kanban_sources where contact_id=id_to_refresh and is_test;
    perform public.crm_kanban_refresh(id_to_refresh);
  end loop;
  delete from public.crm_kanban_events where event_type in ('created','source_update') and payload->>'is_test'='true';
  delete from public.crm_kanban_test_sample;
  return jsonb_build_object('removed_test_contacts',removed,'cutoff','2026-11-13','include_history',false);
end $$;

