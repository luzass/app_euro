create table if not exists public.crm_kanban_loss_reasons (
  id uuid primary key default gen_random_uuid(),
  seed_key text unique,
  name text not null check(length(btrim(name)) between 3 and 120 and public.crm_kanban_key(name)<>''),
  active boolean not null default true,
  requires_note boolean not null default false check(seed_key is distinct from 'other' or requires_note),
  version integer not null default 1,
  created_at timestamptz not null default now(),updated_at timestamptz not null default now()
);
create unique index if not exists crm_kanban_loss_reasons_name_key on public.crm_kanban_loss_reasons(public.crm_kanban_key(name));
create table if not exists public.crm_kanban_loss_reason_history (
  id bigint generated by default as identity primary key,
  reason_id uuid not null references public.crm_kanban_loss_reasons(id),
  actor_id uuid references public.profiles(id),
  before_data jsonb,after_data jsonb not null,created_at timestamptz not null default now()
);
